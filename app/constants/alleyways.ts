export function findAlleywayByName(name: string): Alleyway | undefined {
    return alleyways.find(a => a.name === name);
}

export function getAlleywayMidpoint(alley: Alleyway): [number, number] {
    const mid = alley.positions[Math.floor(alley.positions.length / 2)];
    return [mid[0], mid[1]];
}
